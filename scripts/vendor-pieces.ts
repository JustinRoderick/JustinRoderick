// Regenerates src/pieces.ts from assets/cburnett/*.svg. Pass --fetch to refresh the SVGs from lichess first.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const SOURCE = "https://raw.githubusercontent.com/lichess-org/lila/master/public/piece/cburnett";
const dir = join(import.meta.dirname, "../assets/cburnett");
const out = join(import.meta.dirname, "../src/pieces.ts");
const names = ["w", "b"].flatMap((color) => ["K", "Q", "R", "B", "N", "P"].map((role) => color + role));

if (process.argv.includes("--fetch")) {
  await mkdir(dir, { recursive: true });
  for (const name of names) {
    const response = await fetch(`${SOURCE}/${name}.svg`);
    if (!response.ok) throw new Error(`${name}.svg: HTTP ${response.status}`);
    await writeFile(join(dir, `${name}.svg`), await response.text());
  }
}

const symbols: string[] = [];
for (const name of names) {
  const svg = (await readFile(join(dir, `${name}.svg`), "utf8")).trim();
  const match = /^(?:<\?xml[^>]*\?>\s*)?<svg\b[^>]*\bviewBox="([^"]+)"[^>]*>([\s\S]*)<\/svg>$/.exec(svg);
  if (!match) throw new Error(`${name}.svg: unexpected markup`);
  const [, viewBox, body] = match;
  symbols.push(`<symbol id="${name}" viewBox="${viewBox}">${body!.trim()}</symbol>`);
}

await writeFile(
  out,
  `// Generated by scripts/vendor-pieces.ts from the cburnett set by Colin M.L. Burnett (GPLv2+ / CC BY-SA 3.0).
// Do not edit by hand.
export const PIECE_SYMBOLS = ${JSON.stringify(symbols.join(""))};
`,
);
console.log(`wrote ${symbols.length} symbols to src/pieces.ts`);
